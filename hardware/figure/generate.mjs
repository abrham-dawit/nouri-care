// Nouri figure: parametric, print-ready rebuild of "Part Studio 1 - Part 1".
//
//   cd hardware/figure && npm install && npm run build
//
// Writes one STL per printed part to ./print and an assembled preview to ./preview.
// All dimensions are millimetres. Change a number below and rebuild.

import Module from "manifold-3d";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const P = {
  body: {
    rx: 57, // half-width of the egg at its base (original: 114 mm outside)
    ry: 71.5, // half-height of the egg (original: 143 mm outside)
    depth: 58, // how far the dome bulges forward
    wall: 2.4, // 6 lines with a 0.4 mm nozzle
    segments: 160,
  },
  // Openings in the face (centre measured from the middle of the egg)
  window: { d: 52.5, x: 0, y: 27 }, // round display window
  sensor: { d: 10, x: 0, y: -21 }, // small hole below the window
  // Screw bosses for M3 heat-set inserts (typical insert: ⌀4.0–4.2 hole, 5.7 mm long)
  boss: {
    od: 8,
    hole: 4.2,
    holeDepth: 6.5,
    positions: [
      [14, 58],
      [-14, 58],
      [14, -58],
      [-14, -58],
    ],
  },
  // Back plate (egg + legs as one flat piece) and the separate arms share this thickness
  plate: { thickness: 5, screwHole: 3.4, countersinkD: 6.6 },
  // Puzzle-style dovetail joining each arm to the back plate
  dovetail: { depth: 12, neck: 10, end: 15, clearance: 0.2 },
};

const here = dirname(fileURLToPath(import.meta.url));
const outlines = JSON.parse(readFileSync(join(here, "outlines.json"), "utf8"));

const wasm = await Module();
wasm.setup();
const { Manifold, CrossSection } = wasm;

/* ───────────── helpers ───────────── */

const ellipse = (rx, ry, n = P.body.segments) => new CrossSection([Array.from({ length: n }, (_, i) => [rx * Math.cos((2 * Math.PI * i) / n), ry * Math.sin((2 * Math.PI * i) / n)])]);
const shape = (pts) => new CrossSection([pts], "NonZero");
const cyl = (h, r, segs = 64) => Manifold.cylinder(h, r, r, segs);

function writeSTL(path, manifold) {
  const mesh = manifold.getMesh();
  const { vertProperties: v, triVerts: t, numProp: np } = mesh;
  const tris = t.length / 3;
  const buf = Buffer.alloc(84 + tris * 50);
  buf.write("Nouri figure - generated by generate.mjs (units: mm)", 0, "ascii");
  buf.writeUInt32LE(tris, 80);
  for (let i = 0; i < tris; i++) {
    const p = [0, 1, 2].map((k) => [v[t[i * 3 + k] * np], v[t[i * 3 + k] * np + 1], v[t[i * 3 + k] * np + 2]]);
    const u = p[1].map((x, j) => x - p[0][j]), w = p[2].map((x, j) => x - p[0][j]);
    const nrm = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]];
    const len = Math.hypot(...nrm) || 1;
    const o = 84 + i * 50;
    nrm.forEach((x, j) => buf.writeFloatLE(x / len, o + j * 4));
    p.flat().forEach((x, j) => buf.writeFloatLE(x, o + 12 + j * 4));
  }
  writeFileSync(path, buf);
}

function report(name, m) {
  const b = m.boundingBox();
  const size = [0, 1, 2].map((i) => +(b.max[i] - b.min[i]).toFixed(1));
  const info = { part: name, size_mm: size, volume_cm3: +(m.volume() / 1000).toFixed(1), triangles: m.numTri(), genus: m.genus(), status: String(m.status()) };
  console.log(`${name.padEnd(14)} ${size.join(" × ").padEnd(22)} ${String(info.volume_cm3).padStart(6)} cm³  genus ${info.genus}`);
  return info;
}

/* ───────────── front shell ───────────── */

const { rx, ry, depth, wall, segments } = P.body;
const outerSolid = Manifold.sphere(1, segments).scale([rx, ry, depth]).trimByPlane([0, 0, 1], 0);
const innerVoid = Manifold.sphere(1, segments).scale([rx - wall, ry - wall, depth - wall]);
let shell = outerSolid.subtract(innerVoid);

// Bosses grow from the rim plane until they merge into the dome wall.
const bosses = Manifold.union(P.boss.positions.map(([x, y]) => cyl(depth, P.boss.od / 2, 48).translate([x, y, 0]))).intersect(outerSolid);
shell = shell.add(bosses);

const holes = [
  cyl(depth + 10, P.window.d / 2, 128).translate([P.window.x, P.window.y, -1]),
  cyl(depth + 10, P.sensor.d / 2, 48).translate([P.sensor.x, P.sensor.y, -1]),
  ...P.boss.positions.map(([x, y]) => cyl(P.boss.holeDepth + 0.01, P.boss.hole / 2, 32).translate([x, y, -0.01])),
];
shell = shell.subtract(Manifold.union(holes));

/* ───────────── back plate + arms ───────────── */

const t = P.plate.thickness;
const egg = ellipse(rx, ry);
const legs = CrossSection.union([shape(outlines.legRight), shape(outlines.footRight), shape(outlines.legLeft), shape(outlines.footLeft)]);

/**
 * Joint where an arm meets the egg, placed at the arm's closest point to the body.
 * Returns the dovetail (wide end inside the egg, neck at its edge) and a bridge
 * that extends the arm to the egg in case the original outline stops short of it.
 */
function jointFor(armPts) {
  const root = armPts.reduce((best, p) => ((p[0] / rx) ** 2 + (p[1] / ry) ** 2 < (best[0] / rx) ** 2 + (best[1] / ry) ** 2 ? p : best));
  const len = Math.hypot(root[0], root[1]);
  const u = [root[0] / len, root[1] / len], v = [-u[1], u[0]];
  const s = 1 / Math.hypot(u[0] / rx, u[1] / ry); // centre → egg edge along u
  const edge = [u[0] * s, u[1] * s];
  const gap = Math.max(0, len - s); // how far the arm outline is from the egg
  const at = (a, b) => [edge[0] + a * u[0] + b * v[0], edge[1] + a * u[1] + b * v[1]];
  const { depth: d, neck, end } = P.dovetail;
  const tab = shape([at(1, -neck / 2), at(1, neck / 2), at(-d, end / 2), at(-d, -end / 2)]);
  const bridge = shape([at(-1, -neck * 0.9), at(-1, neck * 0.9), at(gap + 6, neck * 1.2), at(gap + 6, -neck * 1.2)]);
  return { tab, bridge };
}

const armPts = { armLeft: outlines.armLeft, armRight: outlines.armRight };
const joints = Object.fromEntries(Object.entries(armPts).map(([k, pts]) => [k, jointFor(pts)]));
const arms = Object.fromEntries(Object.entries(armPts).map(([k, pts]) => [k, shape(pts).add(joints[k].bridge)]));
const tabs = Object.fromEntries(Object.entries(joints).map(([k, j]) => [k, j.tab]));

let plateCS = egg.add(legs);
for (const tab of Object.values(tabs)) plateCS = plateCS.subtract(tab.offset(P.dovetail.clearance, "Miter"));
let plate = plateCS.extrude(t);

// Countersunk M3 screw holes, countersink on the bed side (the back of the figure).
const csH = (P.plate.countersinkD - P.plate.screwHole) / 2;
const screwCuts = P.boss.positions.map(([x, y]) =>
  Manifold.union([
    cyl(t + 2, P.plate.screwHole / 2, 32).translate([x, y, -1]),
    Manifold.cylinder(csH + 0.01, P.plate.countersinkD / 2, P.plate.screwHole / 2, 32).translate([x, y, -0.01]),
  ]),
);
plate = plate.subtract(Manifold.union(screwCuts));

const armParts = Object.fromEntries(Object.entries(arms).map(([k, a]) => [k, a.subtract(egg).add(tabs[k]).extrude(t)]));

/* ───────────── output ───────────── */

const printDir = join(here, "print"), previewDir = join(here, "preview");
mkdirSync(printDir, { recursive: true });
mkdirSync(previewDir, { recursive: true });

console.log("part           size (mm)              volume");
const parts = {
  "front-shell": shell, // print rim-down
  "back-plate": plate, // print flat, countersinks down
  "arm-left": armParts.armLeft,
  "arm-right": armParts.armRight,
};
const summary = Object.entries(parts).map(([name, m]) => {
  writeSTL(join(printDir, `${name}.stl`), m);
  return report(name, m);
});

// Assembled preview (not for printing): plate behind, shell on top, arms in place.
const assembled = Manifold.union([plate, armParts.armLeft, armParts.armRight, shell.translate([0, 0, t])]);
writeSTL(join(previewDir, "assembled.stl"), assembled);
summary.push(report("assembled", assembled));
writeFileSync(join(previewDir, "summary.json"), JSON.stringify({ parameters: P, parts: summary }, null, 2));
